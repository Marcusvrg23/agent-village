// Asset build: npm run build:sprites (uses the project's Electron as a deterministic Canvas 2D renderer).
// Derives Life Mode character layers from the official artwork, which itself stays untouched:
// per station a clean plate patch (character removed, room retouched by an authored recipe),
// masked body/head sprites and foreground occluders, plus public/sprites/sprites.css geometry.
'use strict';
const { app, BrowserWindow, nativeImage } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { stations } = require('./sprite-lib/stations.cjs');

const ROOT = path.resolve(__dirname, '..');
const ART = path.join(ROOT, 'public', 'quality-ops-room-reference.webp');
const OUT = path.join(ROOT, 'public', 'sprites');
const only = process.argv.find((a) => a.startsWith('--only='))?.slice(7).split(',');
const previewDir = process.argv.find((a) => a.startsWith('--preview='))?.slice(10);

app.whenReady().then(async () => {
  try {
    const win = new BrowserWindow({ show: false, webPreferences: { offscreen: true } });
    const page = path.join(os.tmpdir(), 'ops-room-sprite-build.html');
    fs.writeFileSync(page, `<body><script>${fs.readFileSync(path.join(__dirname, 'sprite-lib', 'compose.js'), 'utf8')}</script></body>`);
    await win.loadFile(page);
    const selected = Object.fromEntries(Object.entries(stations).filter(([role]) => !only || only.includes(role)));
    const built = await win.webContents.executeJavaScript(`new Promise((resolve, reject) => {
      const art = new Image(); art.onerror = () => reject(new Error('art decode failed'));
      const all = window.silhouettesOf(${JSON.stringify(stations)});
      art.onload = () => { try { resolve(Object.fromEntries(Object.entries(${JSON.stringify(selected)}).map(([role, def]) => [role, window.composeStation(art, def, role, all)]))); } catch (e) { reject(e); } };
      art.src = ${JSON.stringify('file:///' + ART.replaceAll('\\', '/'))}; })`);
    win.destroy();
    fs.mkdirSync(OUT, { recursive: true });
    for (const [role, parts] of Object.entries(built)) {
      for (const [kind, { rect, url }] of Object.entries(parts)) {
        const image = nativeImage.createFromDataURL(url);
        fs.writeFileSync(path.join(OUT, `${role.toLowerCase()}-${kind}.png`), image.toPNG());
        if (previewDir) {
          fs.mkdirSync(previewDir, { recursive: true });
          fs.writeFileSync(path.join(previewDir, `${role}-${kind}.png`), image.resize({ width: rect.w * 4, quality: 'good' }).toPNG());
        }
      }
      console.log(`${role}: ${Object.entries(parts).map(([k, v]) => `${k} ${v.rect.w}x${v.rect.h}@${v.rect.x},${v.rect.y}`).join(' | ')}`);
    }
    // Geometry for every station built so far (merged so --only rebuilds keep the others).
    const geometryFile = path.join(OUT, 'geometry.json');
    const geometry = fs.existsSync(geometryFile) ? JSON.parse(fs.readFileSync(geometryFile, 'utf8')) : {};
    for (const [role, parts] of Object.entries(built)) geometry[role] = Object.fromEntries(Object.entries(parts).map(([k, v]) => [k, v.rect]));
    fs.writeFileSync(geometryFile, JSON.stringify(geometry, null, 2) + '\n');
    const css = ['/* Generated by scripts/build-sprites.cjs from the official artwork. Do not edit. */'];
    for (const [role, parts] of Object.entries(geometry)) {
      const name = role.toLowerCase(); const def = stations[role];
      const figure = [parts.head, parts.body].filter(Boolean);
      const x0 = Math.min(...figure.map((r) => r.x)); const x1 = Math.max(...figure.map((r) => r.x + r.w));
      const y0 = Math.min(...figure.map((r) => r.y)); const y1 = Math.max(...figure.map((r) => r.y + r.h));
      const rig = def.rig ? ` --hip-x: ${def.rig.hip[0]}; --hip-y: ${def.rig.hip[1]}; --pants: ${def.rig.pants}; --shoe: ${def.rig.shoe}; --sock: ${def.rig.sock};` : '';
      // Head pivot (matches .head transform-origin 50% 88%) so face details like eyelids turn with the head.
      const pivot = parts.head ? ` --hox: ${(parts.head.x + parts.head.w / 2).toFixed(1)}; --hoy: ${(parts.head.y + parts.head.h * 0.88).toFixed(1)};` : '';
      css.push(`.station.${name} { --cx: ${Math.round((x0 + x1) / 2)}; --cy: ${Math.round((y0 + y1) / 2)}; --top: ${y0};${pivot}${rig} }`);
      for (const [kind, r] of Object.entries(parts)) css.push(`.station.${name} .${kind} { --x: ${r.x}; --y: ${r.y}; --w: ${r.w}; --h: ${r.h}; }`);
    }
    fs.writeFileSync(path.join(OUT, 'sprites.css'), css.join('\n') + '\n');
    app.exit(0);
  } catch (error) {
    console.error(error);
    app.exit(1);
  }
});
